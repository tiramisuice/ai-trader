/** Get display name for a ticker. Returns "Name (TICKER)" or just "TICKER" if unknown. */
export function getStockName(ticker: string): string {
  return TW_NAMES[ticker] ?? US_NAMES[ticker] ?? null
}

/** Format ticker with name: "台積電 2330.TW" or "Apple AAPL" or just "TICKER" */
export function formatTicker(ticker: string): { name: string | null; ticker: string } {
  return { name: getStockName(ticker), ticker }
}
